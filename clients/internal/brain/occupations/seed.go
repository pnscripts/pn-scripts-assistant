/*
 * The taxonomy the program ships with.
 *
 * About a hundred jobs and two hundred capabilities: enough that the shape of
 * the thing is visible in every category, weighted towards the work actually
 * done here so the common case is described well rather than evenly. It is
 * not meant to be complete — completeness is what the importers are for — but
 * it is meant to be true, and nothing is in it that nobody does.
 *
 * Written as text rather than as structs because a table of a hundred jobs
 * with six fields each is read far more often than it is compiled, and the
 * version that can be read down a column is the version that stays correct.
 */

// entry is one job in the table below. Empty status means established, empty
// risk means low, and a capability marked with a leading "-" is one the job
// often involves rather than one it is.
type entry struct {
	id      string
	title   string
	aliases string
	what    string
	needs   string
	status  string
	risk    string
	watch   bool

	// What somebody in this job is responsible for, what they produce, what
	// they are expected to know, and what good work is judged on. One per
	// line. Empty is honest for a job nobody here is going to hold — the
	// importers fill those in from a real classification.
	does     string
	makes    string
	knows    string
	measured string

	// ladder overrides the one its category uses, for a job whose career
	// steps are its own.
	ladder string

	// near is other jobs worth considering instead, as bare ids within the
	// same category unless they carry a dot.
	near string
}

type shelf struct {
	category string
	jobs     []entry
}

/*
 * Seed is the built-in taxonomy, ready to be written to a brain.
 *
 * Capabilities come out of the same table: a job names what it needs, and
 * every name it uses is defined once in capabilityNames. That way a job
 * cannot refer to a capability nobody has described, and there is one place
 * to read what the program thinks "API design" means.
 */
func Seed() ([]store.Occupation, []store.Capability) {
	jobs := []store.Occupation{}

	for _, shelf := range seed {
		for _, e := range shelf.jobs {
			jobs = append(jobs, store.Occupation{
				ID:          shelf.category + "." + e.id,
				Title:       e.title,
				Aliases:     splitAliases(e.aliases),
				Category:    shelf.category,
				Description: e.what,
				Status:      orElse(e.status, store.Established),
				Risk:        orElse(e.risk, store.RiskLow),
				Oversight:   e.watch,
				CameFrom:    store.FromSeed,
				Needs:       needsOf(e.needs),

				Does:       lines(e.does),
				Makes:      lines(e.makes),
				Knows:      lines(e.knows),
				MeasuredBy: lines(e.measured),
				Ladder:     ladderFor(shelf.category, e.ladder),
				Near:       near(shelf.category, e.near),
			})
		}
	}

	capabilities := make([]store.Capability, 0, len(capabilityNames))

	for id, name := range capabilityNames {
		kind := store.CapabilitySkill

		if knowledge[id] {
			kind = store.CapabilityKnowledge
		}

		capabilities = append(capabilities, store.Capability{
			ID: id, Name: name, Kind: kind, CameFrom: store.FromSeed,
		})
	}

	return jobs, capabilities
}

/*
 * Career ladders, which are not one ladder.
 *
 * "Intern, junior, mid, senior, staff, principal" belongs to software and
 * almost nowhere else. A surgeon is a trainee and then a consultant; a
 * solicitor is a trainee and then a partner; an electrician is an apprentice
 * and then a master. Applying the software ladder to all of them would be
 * wrong for most and would look authoritative while being so — and the
 * seniority somebody is given is written into their agent file, so a wrong
 * rung is a wrong word in front of them every day.
 */
var ladders = map[string][]string{
	Leadership:  {"manager", "director", "vice_president", "chief"},
	Software:    {"intern", "junior", "mid", "senior", "staff", "principal"},
	AI:          {"intern", "junior", "mid", "senior", "staff", "principal"},
	Data:        {"intern", "junior", "mid", "senior", "staff", "principal"},
	Security:    {"junior", "mid", "senior", "staff", "principal"},
	Product:     {"associate", "mid", "senior", "principal", "head"},
	Design:      {"junior", "mid", "senior", "lead", "head"},
	Health:      {"trainee", "junior", "specialist", "consultant"},
	Legal:       {"trainee", "associate", "senior_associate", "partner"},
	Finance:     {"assistant", "qualified", "senior", "head"},
	Science:     {"assistant", "researcher", "senior_researcher", "principal_investigator"},
	Education:   {"assistant", "teacher", "senior_teacher", "head"},
	Trades:      {"apprentice", "qualified", "experienced", "master"},
	Engineering: {"graduate", "engineer", "senior", "chartered", "principal"},
	Government:  {"officer", "senior_officer", "head", "director"},
}

func ladderFor(category, own string) []string {
	if own != "" {
		return lines(strings.ReplaceAll(own, ",", "\n"))
	}

	return ladders[category]
}

// near fills in the category for a bare id, so the table can say "api_engineer"
// rather than repeating its own shelf on every line.
func near(category, list string) []string {
	out := []string{}

	for _, id := range strings.Split(list, ",") {
		if id = strings.TrimSpace(id); id == "" {
			continue
		}

		if !strings.Contains(id, ".") {
			id = category + "." + id
		}

		out = append(out, id)
	}

	if len(out) == 0 {
		return nil
	}

	return out
}

// lines splits a block written one item to a line, which is how
// responsibilities read in the table and how they are stored.
func lines(block string) []string {
	out := []string{}

	for _, line := range strings.Split(block, "\n") {
		if line = strings.TrimSpace(line); line != "" {
			out = append(out, line)
		}
	}

	if len(out) == 0 {
		return nil
	}

	return out
}

func needsOf(list string) []store.Need {
	out := []store.Need{}

	for _, id := range strings.Fields(list) {
		essential := true

		if strings.HasPrefix(id, "-") {
			id, essential = strings.TrimPrefix(id, "-"), false
		}

		out = append(out, store.Need{ID: id, Essential: essential})
	}

	return out
}

func splitAliases(raw string) []string {
	out := []string{}

	for _, one := range strings.Split(raw, "|") {
		if one = strings.TrimSpace(one); one != "" {
			out = append(out, one)
		}
	}

	if len(out) == 0 {
		return nil
	}

	return out
}

func orElse(value, fallback string) string {
	if strings.TrimSpace(value) == "" {
		return fallback
	}

	return value
}

