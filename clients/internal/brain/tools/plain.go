// Plain is what a capability does, in a sentence a person reads, in English
// ("en") or Bulgarian ("bg"). Empty when there is no line for it, which a
// test treats as a fault for anything built in.
func Plain(name, lang string) string {
	pair, ok := plainWords[name]
	if !ok {
		return ""
	}

	if lang == "bg" {
		return pair[1]
	}

	return pair[0]
}
